export type Locale = "zh-CN" | "en";
export type Appearance = "system" | "light" | "dark";

export function read(key: string) {
  try { return localStorage.getItem(key); } catch { return null; }
}
export function write(key: string, value: string) {
  try { localStorage.setItem(key, value); } catch { /* In-memory preferences still work. */ }
}
const storedLocale = read("starstack.language");
let language: Locale = storedLocale === "en" || storedLocale === "zh-CN" ? storedLocale : navigator.language.toLowerCase().startsWith("zh") ? "zh-CN" : "en";
export const getLocale = () => language;
export function setLocale(value: Locale) {
  language = value;
  write("starstack.language", value);
}
export function getAppearance(): Appearance {
  const stored = read("starstack.theme");
  return stored === "dark" || stored === "light" ? stored : "system";
}

